def affected_by(truth: dict[str, Any], tool_id: str, window: str) -> list[str]:
    """Everyone an error on this tool reached in the window, across its error sources."""
    rows = truth["lookups"]["errors_seen"][window]
    return sorted({name for r in rows if r["tool_id"] == tool_id for name in r["affected"]})


def build() -> str:
    """The exact text of questions_heldout.json."""
    truth = json.loads((DATA_DIR / "ground_truth.json").read_text(encoding="utf-8"))
    questions: list[dict[str, Any]] = []
    for qid, question, lookup, values in ANSWERABLE:
        expect = expectation(truth, {"calls": [lookup], "values": values})
        if qid == "hi09":
            expect["texts"] = affected_by(truth, "proposal_writer", "7d")
        questions.append(
            {
                "id": qid,
                "tier": TIERS[qid[:2]],
                "question": question,
                "refuse": False,
                "adversarial": False,
                "expect": expect,
            }
        )
    for qid, question, adversarial in REFUSALS:
        questions.append(
            {
                "id": qid,
                "tier": "refusal",
                "question": question,
                "refuse": True,
                "adversarial": adversarial,
                "expect": None,
            }
        )
    document = {"header": HEADER, "questions": questions}
    return json.dumps(document, indent=1, ensure_ascii=True) + "\n"


if __name__ == "__main__":
    (EVALS_DIR / "questions_heldout.json").write_text(build(), encoding="utf-8")
    print("evals: held-out questions written")

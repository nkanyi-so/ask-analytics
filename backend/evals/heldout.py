TIERS = {"hd": "direct", "hi": "indirect", "hc": "comparison"}


def top(by: str, field: str) -> Spec:
    return {"call": 0, "list": "rows", "top": by, "field": field}


def tool(name: str, field: str) -> Spec:
    return row("tool_name", name, field)


def person(name: str, field: str) -> Spec:
    return row("name", name, field)


